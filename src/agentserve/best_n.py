"""Pick each baseline's best fixed N per memory budget from a report, and print sweep grids
that run every baseline/budget pair at its best N (Phase 1 Stage A2).

The rule is fixed so the choice is reproducible: among resident-cache configurations at the
tuning rate, the N with the highest mean goodput on development workloads (ties go to the
smaller N, the cheaper setting).

    python -m agentserve.best_n REPORT/configurations.csv --rates 0.025 0.05 >> configs/phase1-dev.toml
"""

from __future__ import annotations

import argparse
import csv
import math
import sys
from pathlib import Path

GOODPUT = "goodput_tasks_per_min_mean"


def best_n(rows: list[dict[str, str]], tuning_rate: float = 0.1) -> dict[tuple[str, int], int]:
    """(policy, memory budget) -> the N with the highest mean goodput at ``tuning_rate``."""
    best: dict[tuple[str, int], tuple[float, int]] = {}
    for row in rows:
        if row["cache_policy"] != "resident" or not math.isclose(float(row["arrival_rate_per_s"]), tuning_rate):
            continue
        goodput = float(row[GOODPUT])
        if math.isnan(goodput):
            continue
        key = (row["policy"], int(float(row["memory_budget_tokens"])))
        n = int(float(row["concurrency"]))
        if key not in best or (goodput, -n) > (best[key][0], -best[key][1]):
            best[key] = (goodput, n)
    return {key: n for key, (_, n) in best.items()}


def grids(choice: dict[tuple[str, int], int], rates: list[float], budgets: list[int] | None = None) -> str:
    out = ["", "# Stage A2, generated by agentserve.best_n from the Stage A1 report"]
    for (policy, budget), n in sorted(choice.items()):
        if budgets and budget not in budgets:
            continue
        out += [
            "[[grid]]",
            f'policy = ["{policy}"]',
            f"concurrency = [{n}]            # best {policy} N at {budget}",
            f"memory_budget = [{budget}]",
            f"arrival_rate = [{', '.join(str(r) for r in rates)}]",
            'cache_policy = ["resident"]',
            "",
        ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("configurations", type=Path, help="a report's configurations.csv")
    parser.add_argument("--rates", type=float, nargs="+", required=True, help="arrival rates for the grids")
    parser.add_argument("--tuning-rate", type=float, default=0.1)
    parser.add_argument("--budgets", type=int, nargs="*", default=[16384, 32768])
    ns = parser.parse_args(argv)
    with open(ns.configurations, newline="", encoding="utf-8") as f:
        choice = best_n(list(csv.DictReader(f)), ns.tuning_rate)
    for (policy, budget), n in sorted(choice.items()):
        print(f"best N: {policy} at {budget} -> {n}", file=sys.stderr)
    print(grids(choice, ns.rates, ns.budgets))
    return 0


if __name__ == "__main__":
    sys.exit(main())
