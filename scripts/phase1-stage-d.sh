#!/usr/bin/env bash
# Phase 1 Stage D on machine B, unattended: run D1 (N = 16 at 32k), pick each baseline's best
# N per budget from machine A's A1 report pooled with this machine's report, append the A2
# grids, run A2, and rebuild the report. Run inside tmux from the repo root.
#   bash scripts/phase1-stage-d.sh MACHINE_A_CONFIGURATIONS_CSV [OUT]
set -euo pipefail

A_CSV="$1"
CONFIG=configs/phase1-dev-b.toml
OUT="${2:-/workspace/results/phase1-dev-b}"
export PATH="$HOME/.local/bin:$PATH"

[ -f "$A_CSV" ] || { echo "machine A's configurations.csv not found: $A_CSV" >&2; exit 1; }

uv run agentserve sweep "$CONFIG" --out "$OUT"
uv run agentserve report "$OUT" --out "$OUT/report"

if grep -q "generated by agentserve.best_n" "$CONFIG"; then
    echo "A2 grids already in $CONFIG"
else
    uv run python -m agentserve.best_n "$A_CSV" "$OUT/report/configurations.csv" --rates 0.025 0.05 >> "$CONFIG"
fi

uv run agentserve sweep "$CONFIG" --out "$OUT"
uv run agentserve report "$OUT" --out "$OUT/report"
echo "Stage D complete"
