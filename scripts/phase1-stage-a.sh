#!/usr/bin/env bash
# Phase 1 Stage A on the pod, unattended: finish A1 (resumes, so only missing runs run), pick
# each baseline's best N per budget from the A1 report, append the A2 grids to the sweep
# config, then run A2 and rebuild the report. Run inside tmux from the repo root.
set -euo pipefail

CONFIG=configs/phase1-dev.toml
OUT="${1:-/workspace/results/phase1-dev}"
export PATH="$HOME/.local/bin:$PATH"

uv run agentserve sweep "$CONFIG" --out "$OUT"
uv run agentserve report "$OUT" --out "$OUT/report"

if grep -q "generated by agentserve.best_n" "$CONFIG"; then
    echo "A2 grids already in $CONFIG"
else
    uv run python -m agentserve.best_n "$OUT/report/configurations.csv" --rates 0.025 0.05 >> "$CONFIG"
fi

uv run agentserve sweep "$CONFIG" --out "$OUT"
uv run agentserve report "$OUT" --out "$OUT/report"
echo "Stage A complete"
